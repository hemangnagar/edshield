"""Generate synthetic tutoring transcripts and student essays with injected
PII, in the exact PIILO JSON format (tokens / trailing_whitespace / labels).

Two uses:
  * a benchmark you can run before the real corpus is downloaded,
  * augmentation for train.py (`--extra data/synthetic.json`), which the
    competition winners found essential for the rare labels (PHONE_NUM,
    STREET_ADDRESS, ID_NUM).

    python eval/synthetic_bench.py --n 500 --out data/synthetic.json --seed 1

All values are generated by Faker; no real people.
"""

from __future__ import annotations

import argparse
import json
import random
import re
from pathlib import Path

from faker import Faker

TOKEN_RE = re.compile(r"\w+|[^\w\s]", re.UNICODE)

ESSAY_OPENERS = [
    "In this reflection I want to talk about a problem in my community and how we could fix it.",
    "For this assignment, we were asked to apply the design thinking process to a real situation.",
    "The topic I chose is how technology changes the way students learn.",
    "My project looked at food waste in our cafeteria and what we could do about it.",
    "This essay is about what I learned from interviewing people about recycling in my neighborhood.",
]
ESSAY_BODY = [
    "First, I gathered information by talking to people and reading articles online.",
    "Then I looked for patterns in what everyone said and tried to define the real problem.",
    "One thing that surprised me was how many people did not know the rules.",
    "I think a good solution would be to start small and test it with a few classes before going school-wide.",
    "The hardest part was staying organized and keeping track of all my notes.",
    "If I did this again I would spend more time on the prototype stage.",
    "Overall this project taught me that listening carefully matters more than having a fancy idea.",
]
TUTOR_LINES = [
    "Tutor: Good afternoon! What are we working on today?",
    "Tutor: Let's start with the first problem. What do you think the question is asking?",
    "Tutor: Nice, that's exactly right. Can you explain why you subtracted here?",
    "Tutor: Let's slow down. What's the unit on that number?",
    "Tutor: Great work today. Try problems 4 through 8 before next time.",
    "Tutor: Remember to show each step so I can see your reasoning.",
]
STUDENT_LINES = [
    "Student: I think we need to find the slope first.",
    "Student: I got 42 but I'm not sure that's right.",
    "Student: Oh, because the two triangles are similar?",
    "Student: Can we go over the homework from last week?",
    "Student: I don't really get why the negative sign flips.",
    "Student: Okay that makes sense now.",
]


def inject(fake: Faker, rng: random.Random):
    """Return (sentence, [(value, label), ...]) with the PII values embedded."""
    first, last = fake.first_name(), fake.last_name()
    full = f"{first} {last}"
    options = [
        (f"My name is {full} and I am in {rng.choice(['7th', '8th', '9th', '10th'])} grade.", [(full, "NAME_STUDENT")]),
        (f"Student: Hi, this is {first}.", [(first, "NAME_STUDENT")]),
        (f"You can reach me at {fake.free_email()} if you have questions.", [(None, "EMAIL")]),
        (f"My phone number is {fake.numerify(rng.choice(['###-###-####', '(###) ###-####', '###.###.####']))}.", [(None, "PHONE_NUM")]),
        (f"My student ID is {fake.numerify(rng.choice(['#######', '##-######', 'S########']))}.", [(None, "ID_NUM")]),
        (f"Follow my project on instagram @{fake.user_name()} for updates.", [(None, "USERNAME")]),
        (f"My username on the class site is {fake.user_name()}.", [(None, "USERNAME")]),
        (f"I posted the video on {rng.choice(['https://youtube.com/@', 'https://github.com/', 'https://www.tiktok.com/@'])}{fake.user_name()} last night.", [(None, "URL_PERSONAL")]),
        (f"We live at {fake.street_address()}, {fake.city()}, {fake.state_abbr()} {fake.postcode()}.", [(None, "STREET_ADDRESS")]),
        (f"Interviewed by {full} on {fake.date(pattern='%B %d, %Y')}.", [(full, "NAME_STUDENT")]),
        (f"{first} said the survey took about ten minutes.", [(first, "NAME_STUDENT")]),
    ]
    sent, spans = rng.choice(options)
    resolved = []
    for val, label in spans:
        if val is None:
            # recover the injected value from the sentence by label-specific regex
            pat = {
                "EMAIL": r"[\w.+-]+@[\w-]+\.[\w.]+",
                "PHONE_NUM": r"\(?\d{3}\)?[\s.-]?\d{3}[\s.-]?\d{4}",
                "ID_NUM": r"(?:S\d{8}|\d{2}-\d{6}|\d{7})",
                "USERNAME": r"(?<=@)[\w.]+|(?<=is )[\w.]+(?=\.)",
                "URL_PERSONAL": r"https?://\S+?(?= last)",
                "STREET_ADDRESS": r"(?<=live at ).+?(?=\.$)",
            }[label]
            m = re.search(pat, sent)
            val = m.group()
        resolved.append((val, label))
    return sent, resolved


def to_piilo(doc_id: int, sentences, spans_per_sentence):
    text = " ".join(sentences)
    char_labels = ["O"] * len(text)
    cursor = 0
    for sent, spans in zip(sentences, spans_per_sentence):
        base = text.index(sent, cursor)
        for val, label in spans:
            s = sent.index(val)
            for i in range(base + s, base + s + len(val)):
                char_labels[i] = label
        cursor = base + len(sent)
    tokens, ws, labels = [], [], []
    prev_label = None
    for m in TOKEN_RE.finditer(text):
        tok = m.group()
        lab = char_labels[m.start()]
        if lab == "O":
            labels.append("O")
        else:
            prefix = "I" if prev_label == lab and (m.start() == 0 or char_labels[m.start() - 1] == lab or text[m.start() - 1] == " ") else "B"
            labels.append(f"{prefix}-{lab}")
        prev_label = lab if lab != "O" else None
        tokens.append(tok)
        ws.append(m.end() < len(text) and text[m.end()] == " ")
    return {"document": doc_id, "full_text": text, "tokens": tokens, "trailing_whitespace": ws, "labels": labels}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=200)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--neg_frac", type=float, default=0.3)
    a = ap.parse_args()

    fake = Faker("en_US")
    fake.seed_instance(a.seed)
    rng = random.Random(a.seed)
    docs = []
    for i in range(a.n):
        transcript = rng.random() < 0.4
        n_sent = rng.randint(5, 9)
        sentences, spans = [], []
        pool = TUTOR_LINES + STUDENT_LINES if transcript else [rng.choice(ESSAY_OPENERS)] + ESSAY_BODY
        for j in range(n_sent):
            if rng.random() > a.neg_frac and rng.random() < 0.45:
                s, sp = inject(fake, rng)
            else:
                s, sp = rng.choice(pool), []
            sentences.append(s)
            spans.append(sp)
        docs.append(to_piilo(i, sentences, spans))
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(docs))
    n_pos = sum(any(l != "O" for l in d["labels"]) for d in docs)
    print(f"wrote {len(docs)} docs ({n_pos} with PII) to {a.out}")


if __name__ == "__main__":
    main()
